import data from './catalog.json'
import images from './images.json'

export type Lang = 'en' | 'hi'
type Text = { en: string; hi: string }
export type StoryParagraph = { heading?: Text; text: Text; isLegend?: boolean; source?: number | null; cited?: number[] }
export type Source = { title: Text; publisher: Text; url?: string }
export type Monument = { id: string; name: Text; city: string; era: string; style: string; location: string; verified: boolean; summary: Text; image: string; sections: StoryParagraph[]; sources: Source[]; related: string[]; lat: number; lng: number }
export type ImageCredit = { url: string; page: string; artist: string; licence: string }

// Generated by backend/tools/fetch_images.py: freely licensed Wikimedia Commons photos with their credits.
export const imageCredits: Record<string, ImageCredit> = images
export const monumentImages: Record<string, string> = Object.fromEntries(Object.entries(imageCredits).map(([id, credit]) => [id, credit.url]))

const featured = ['taj-mahal', 'agra-fort', 'red-fort', 'humayuns-tomb', 'qutb-complex', 'fatehpur-sikri']
const rank = (m: Omit<Monument, 'image'>) => { const i = featured.indexOf(m.id); return i >= 0 ? i : m.verified ? 50 : 99 }
// Generated from the database by backend/tools/export_catalog.py. Sourced stories come first.
export const monuments: Monument[] = (data as Omit<Monument, 'image'>[])
  .toSorted((a, b) => rank(a) - rank(b))
  .map((m) => ({ ...m, image: monumentImages[m.id] ?? `/monuments/${m.id}.svg` }))
export const findMonument = (id: string) => monuments.find((m) => m.id === id)
export const getMonument = (id: string) => findMonument(id) ?? monuments[0]

export const eraOf = (m: { era: string }) => /sultanate/i.test(m.era) ? 'Sultanate' : /mughal/i.test(m.era) ? 'Mughal' : /2[01](st|th) century/i.test(m.era) ? 'Modern' : 'Other'

export function distanceKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }) {
  const rad = Math.PI / 180
  const h = Math.sin((b.lat - a.lat) * rad / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin((b.lng - a.lng) * rad / 2) ** 2
  return 2 * 6371 * Math.asin(Math.sqrt(h))
}

export const nearestMonuments = (origin: Monument, count: number) => monuments
  .filter((m) => m.id !== origin.id)
  .map((m) => ({ monument: m, km: distanceKm(origin, m) }))
  .sort((a, b) => a.km - b.km)
  .slice(0, count)
